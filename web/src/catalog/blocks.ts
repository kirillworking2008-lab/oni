export function formatBlockAddress(prefix: BlockTypeDefinition['prefix'], channelIndex: number): string {
  if (prefix === 'Hi') return 'Hi';
  if (prefix === 'Lo') return 'Lo';
  if (prefix === 'C') {
    const names = ['▲', '▼', '◀', '▶', 'OK', 'ESC'];
    return `C${channelIndex}(${names[(channelIndex - 1) % names.length] ?? ''})`;
  }
  const padded = String(channelIndex).padStart(3, '0');
  return `${prefix}${padded}`;
}

export function formatBlockHeaderLabel(
  def: BlockTypeDefinition,
  channelIndex: number,
  customName: string
): string {
  const base = formatBlockAddress(def.prefix, channelIndex);
  if (def.prefix === 'B') {
    return customName ? `${base}[${customName}]` : `${base}[M${channelIndex}]`;
  }
  return customName ? `${base}(${customName})` : base;
}
